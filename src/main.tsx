import '@fontsource-variable/nunito/wght.css';
import {createRoot} from 'react-dom/client';
import App from './App.tsx';
import './index.css';

createRoot(document.getElementById('root')!).render(<App />);

// Offline support: the service worker (generated in the build) precaches the
// whole game. Development uses no service worker so HMR keeps working.
if (import.meta.env.PROD && 'serviceWorker' in navigator) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register(`${import.meta.env.BASE_URL}sw.js`).catch(() => {
      // Offline mode is optional; the game keeps working online without it.
    });
  });
}
